if (!function_exists('t')) {
    /**
     * Translate one string. Falls back to the Indonesian source text.
     */
    function t($text)
    {
        if (tv_lang() === 'id') {
            return $text;
        }
        return $GLOBALS['TV_DICT'][$text] ?? $text;
    }
}

if (!function_exists('te')) {
    /**
     * Translate and HTML-escape in one step.
     */
    function te($text)
    {
        return htmlspecialchars(t($text), ENT_QUOTES, 'UTF-8');
    }
}

if (!function_exists('tv_lang_url')) {
    /**
     * Current URL with the language swapped, preserving other query params.
     */
    function tv_lang_url($lang)
    {
        $params = $_GET;
        $params['lang'] = $lang;
        $path = strtok($_SERVER['REQUEST_URI'], '?');
        return htmlspecialchars($path . '?' . http_build_query($params), ENT_QUOTES, 'UTF-8');
    }
