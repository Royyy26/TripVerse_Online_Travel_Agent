/**
 * Lightweight two-language support (Indonesian / English).
 *
 * Usage in a page:
 *     require_once __DIR__ . '/_lang.php';
 *     <?= t('Daftar Supplier') ?>
 *
 * The Indonesian copy doubles as the translation key, so any string that has
 * not been translated yet still renders correctly instead of showing a raw
 * key. Switching is done with ?lang=en / ?lang=id and remembered in the
 * session plus a cookie, so the choice survives a new browser session.
 */

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

if (!defined('TV_LANGS')) {
    define('TV_LANGS', ['id' => 'Indonesia', 'en' => 'English']);
}

// ---------------------------------------------------------------------------
// Resolve the active language
// ---------------------------------------------------------------------------
if (isset($_GET['lang']) && array_key_exists($_GET['lang'], TV_LANGS)) {
    $_SESSION['tv_lang'] = $_GET['lang'];
    setcookie('tv_lang', $_GET['lang'], time() + 60 * 60 * 24 * 365, '/');
} elseif (!isset($_SESSION['tv_lang'])) {
    $_SESSION['tv_lang'] = (isset($_COOKIE['tv_lang']) && array_key_exists($_COOKIE['tv_lang'], TV_LANGS))
        ? $_COOKIE['tv_lang']
        : 'id';
}

if (!function_exists('tv_lang')) {
    function tv_lang()
    {
        return $_SESSION['tv_lang'] ?? 'id';
    }
}

